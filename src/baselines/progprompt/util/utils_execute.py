def parse_prog_to_ros(action_str: str) -> str:
    """Convert progprompt action syntax to ROS executor syntax.

    Args:
        action_str: e.g., "walk(kitchen)", "put(apple, table)"

    Returns:
        str: e.g., "navigate_to kitchen", "place_on_top table"
    """
    parsed_action = re.findall(r"(\w+)\s*\((.*)\)", action_str)
    if not parsed_action:
        return action_str

    action_name, action_arg_str = parsed_action[0]
    action_args = [arg.strip().strip("'\"") for arg in action_arg_str.split(",")]
    action_args = [arg for arg in action_args if arg]

    action_map = {
        "walk": "navigate_to",
        "pickup": "grasp",
        "open": "open",
        "close": "close",
        "toggle_on": "toggle_on",
        "toggle_off": "toggle_off",
        "wait": "wait",
        "slice": "slice",
    }

    if action_name == "put":
        target = action_args[1] if len(action_args) >= 2 else action_args[0] if action_args else ""
        return f"place_on_top {target}"

    if action_name in action_map:
        ros_cmd = action_map[action_name]
        arg = action_args[0] if action_args else ("0" if action_name == "wait" else "")
        return f"{ros_cmd} {arg}"

    return f"{action_name} {' '.join(action_args)}"


def _execute_single_action(
    action_str: str,
    action_interface: Any,
    controller,
    log_file,
    elapsed_time: float,
    is_ros: bool = False,
) -> float:
    """Execute a single action string and handle logging and errors."""
    if is_ros:
        try:
            log_file.write(f"Executing: {action_str}\n")
            ros_action = parse_prog_to_ros(action_str)
            log_file.write(
                f"INFO: Converted '{action_str}' to ROS action '{ros_action}'\n"
            )
            success, duration, logs = action_interface.execute_primitive_actions(
                [ros_action]
            )
            if not success:
                raise RuntimeError(f"ROS Action '{ros_action}' failed.")
            log_file.write(f"Action '{action_str}' completed in {duration:.2f}s\n")
            return elapsed_time + duration
        except Exception as e:
            log_file.write(f"ERROR executing ROS action '{action_str}': {e}\n")
            raise

    # This regex handles func('arg'), func ( 'arg' ), func(arg), and func()
    parsed_action = re.findall(r"(\w+)\s*\((.*)\)", action_str)
    if not parsed_action:
        log_file.write(f"ERROR: Could not parse action: {action_str}\n")
        raise ValueError(f"Could not parse action: {action_str}")

    action_name, action_arg_str = parsed_action[0]
    # Handle cases with empty args like drop() and strip quotes/spaces
    action_args = (
        [arg.strip().strip("'\"") for arg in action_arg_str.split(",")]
        if action_arg_str
        else []
    )
    target_obj_name = action_args[0] if action_args else None

    log_file.write(f"Executing: {action_str}\n")
    start_time = time.time()
    action_result = None

    try:
        # Handle parameterless actions or actions with non-object args first
        if action_name == "drop":
            action_result = action_interface.drop()
        elif action_name == "wait":
            duration = float(target_obj_name) if target_obj_name else 0.0
            action_result = action_interface.wait(duration)
        else:
            # All other actions require an object ID
            if not target_obj_name:
                raise ValueError(
                    f"Action '{action_name}' requires an object argument, but none was provided."
                )

            # --- Target Refinement (Sink -> SinkBasin) ---
            # For 'put' actions targeting a 'Sink', we must target 'SinkBasin' instead.
            if action_name == "put" and "sink" in target_obj_name.lower():
                log_file.write(
                    f"INFO: Refining target from '{target_obj_name}' to 'SinkBasin' for put action.\n"
                )
                target_obj_name = "SinkBasin"
            # --- End of Target Refinement ---

            # Now, get the object ID for the actual action
            log_file.write(
                f"INFO: Searching for object ID for target '{target_obj_name}'.\n"
            )
            target_obj_id = find_objID(controller, target_obj_name)
            if not target_obj_id:
                log_file.write(
                    f"ERROR: Could not find object ID for target '{target_obj_name}'.\n"
                )
                raise RuntimeError(
                    f"Action failed: Could not find object ID for '{target_obj_name}'."
                )
            log_file.write(
                f"INFO: Found object ID '{target_obj_id}' for target '{target_obj_name}'.\n"
            )

            # Map plan action names to handler methods and execute with the ID
            action_map = {
                "walk": action_interface.move_to,
                "pickup": action_interface.pickup,
                "put": action_interface.put,
                "open": action_interface.open,
                "close": action_interface.close,
                "toggle_on": action_interface.toggle_on,
                "toggle_off": action_interface.toggle_off,
                "slice": action_interface.slice,
            }

            if action_name in action_map:
                action_result = action_map[action_name](target_obj_id)
            else:
                raise ValueError(f"Unknown action: {action_name}")

        # Check for failure
        if action_result is False:
            raise RuntimeError(f"Action '{action_str}' returned failure from handler.")

    except (ValueError, RuntimeError, TypeError) as e:
        log_file.write(f"ERROR executing action '{action_str}': {e}\n")
        raise

    end_time = time.time()
    action_duration = end_time - start_time
    if isinstance(action_result, (int, float)):
        action_duration += action_result  # Add time from simulation (e.g., wait)

    log_file.write(f"Action '{action_str}' completed in {action_duration:.2f}s\n")
    return elapsed_time + action_duration


def simulate_execution(
    controller, test_tasks, gen_plan, log_file, args, logger, action_interface: Any
):
    elapsed_time = 0
    is_ros = getattr(args, "ros", False)

    for task, plan in zip(test_tasks, gen_plan):
        log_file.write(f"Starting simulation for task: {task}\n")
        # Log the raw plan received from the LLM before any processing
        log_file.write(
            f"--- RAW PLAN RECEIVED ---\n{plan}\n-------------------------\n"
        )
        logger.info(f"Raw plan for task '{task}':\n{plan}")
        try:
            subgoals = fun_processing(plan)
        except Exception as e:
            log_file.write(
                f"CRITICAL: Plan parsing failed with an unexpected error. Error: {e}\n"
            )
            logger.error(f"Plan parsing failed. Error: {e}", exc_info=True)
            raise ProgPromptActionFailedError(
                action_name="Plan Parsing", args=(), message=str(e)
            )

        for subgoal in subgoals.keys():
            step = 1
            for action_item in subgoals[subgoal]:
                if step > 50:  # Safety break for long or looping plans
                    log_file.write("WARNING: Exceeded step limit for subgoal.\n")
                    break

                if isinstance(action_item, dict):
                    # It's an assert/else block
                    assert_statement = action_item["assert"]

                    # Execute the assert
                    objs = see_have_ros() if controller is None else see_have(controller)
                    state = "You see: " + objs
                    current_state = (
                        f"{current_state_prompt}\n\n{state}\n\n{assert_statement}\n"
                    )
                    _, check_state = LM_assert(
                        current_state, args.gpt_version, max_tokens=2, stop=["\n"]
                    )

                    log_file.write(
                        f"State check:\n{state}\n{assert_statement}\n{check_state.strip()}\n"
                    )

                    if "False" in check_state:
                        log_file.write("Assert failed. Executing recovery actions.\n")
                        for else_action in action_item["else"]:
                            elapsed_time = _execute_single_action(
                                else_action,
                                action_interface,
                                controller,
                                log_file,
                                elapsed_time,
                                is_ros=is_ros,
                            )
                            step += 1
                    else:
                        log_file.write("Assert passed. Skipping recovery actions.\n")

                elif isinstance(action_item, str):
                    # It's a simple action string
                    elapsed_time = _execute_single_action(
                        action_item,
                        action_interface,
                        controller,
                        log_file,
                        elapsed_time,
                        is_ros=is_ros,
                    )
                    step += 1

    print(f"{round(elapsed_time, 2)=}")
    log_file.write(f"Total time spent : {round(elapsed_time, 2)}")
