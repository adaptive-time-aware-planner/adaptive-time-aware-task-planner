def fun_processing(plan: str) -> dict:
    """Parse the LLM-generated plan into a structured format.

    This function processes a multi-line string representing a plan,
    organizing it into subgoals. It specifically handles the custom
    `assert`/`else` syntax by grouping recovery actions (`else`)
    under their corresponding condition check (`assert`).

    Args:
        plan: The string containing the plan generated by the LLM.

    Returns:
        A dictionary where keys are subgoal names and values are lists
        of actions. Normal actions are strings, while assert/else blocks
        are represented as dictionaries: `{'assert': str, 'else': [str]}`.
    """

    subgoals = {}
    sg = "0"  # Default subgoal key
    subgoals[sg] = []

    lines = plan.split("\n")
    for line in lines:
        stripped_line = line.strip()

        if not stripped_line or "def" in stripped_line:
            continue

        if stripped_line.startswith("#"):
            sg = stripped_line.lstrip("#").strip()
            if sg not in subgoals:
                subgoals[sg] = []
        elif stripped_line.startswith("assert"):
            assert_block = {"assert": stripped_line, "else": []}
            subgoals[sg].append(assert_block)
        elif stripped_line.startswith("else:"):
            # Find the last added assert block in the current subgoal
            if (
                subgoals[sg]
                and isinstance(subgoals[sg][-1], dict)
                and "assert" in subgoals[sg][-1]
            ):
                else_action = stripped_line.split(":", 1)[1].strip()
                subgoals[sg][-1]["else"].append(else_action)
            else:
                # Orphaned 'else', log warning and skip or handle as error
                logger.warning(
                    f"Orphaned 'else' statement found: {stripped_line}. Ignoring."
                )
        else:
            subgoals[sg].append(stripped_line)

    # Remove empty default subgoal if it was not used
    if sg != "0" and not subgoals.get("0"):
        if "0" in subgoals:
            del subgoals["0"]

    print(subgoals)
    return subgoals


def find_objID(controller, obj_type: str) -> str | None:
    """Find object ID by matching object type (exact match).

    This function assumes a fully-observable environment and searches all
    objects. It includes special handling for 'Sink' to find a 'SinkBasin'.

    Args:
        controller: AI2Thor controller.
        obj_type: Object type name to search for (e.g., 'Sink', 'Pot').

    Returns:
        The object ID if a match is found, otherwise None.
    """
    if not obj_type:
        return None

    obj_type_lower = obj_type.lower()
    all_objects = controller.last_event.metadata["objects"]

    # Special handling for 'sink' -> find a 'sinkbasin'
    if obj_type_lower == "sink":
        logger.info("Query is for 'Sink', redirecting to find 'SinkBasin'.")
        for obj in all_objects:
            if obj["objectType"] == "SinkBasin":
                logger.info(f"Found SinkBasin with ID '{obj['objectId']}'.")
                return obj["objectId"]
        logger.warning("Could not find any SinkBasin in the scene.")
        return None

    # Normal object search (exact match)
    for obj in all_objects:
        if obj["objectType"].lower() == obj_type_lower:
            return obj["objectId"]

    return None


